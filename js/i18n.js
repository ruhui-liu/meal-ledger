// 界面语言：中文（默认）/ English
// 用法：t('付给 {name}', { name }) —— 以中文原文为 key，英文模式下查 EN 表，查不到就显示中文。
// 复数：英文里可以写 {n|person|people}，n 为 1 时用前者。
const KEY = 'fz.lang';
let lang = 'zh';
try { lang = localStorage.getItem(KEY) === 'en' ? 'en' : 'zh'; } catch { /* 隐私模式 */ }

export const getLang = () => lang;
export function setLang(l) {
  lang = l === 'en' ? 'en' : 'zh';
  try { localStorage.setItem(KEY, lang); } catch { /* ignore */ }
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
}

export function t(s, p) {
  let out = (lang === 'en' && EN[s]) || s;
  if (p) {
    out = out.replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (m, k, one, many) => (Number(p[k]) === 1 ? one : many));
    out = out.replace(/\{(\w+)\}/g, (m, k) => (k in p ? p[k] : m));
  }
  return out;
}

